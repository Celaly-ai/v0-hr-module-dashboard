function getLocalNeighborhoods(
  province: string,
  district: string,
  query: string,
): NeighborhoodSuggestion[] {
  const provinceKey = normalizeTR(province)
  const districtKey = normalizeTR(district)
  const q = normalizeTR(query)

  if (provinceKey !== "diyarbakir") return []

  const matchedDistrictKey = Object.keys(DIYARBAKIR_NEIGHBORHOODS).find(
    (key) => normalizeTR(key) === districtKey,
  )

  if (!matchedDistrictKey) return []

  return DIYARBAKIR_NEIGHBORHOODS[matchedDistrictKey]
    .filter((name) => normalizeTR(name).includes(q))
    .slice(0, 20)
    .map((name) => ({
      name,
      displayName: `${name} Mahallesi, ${district}, ${province}`,
      lat: Number.NaN,
      lng: Number.NaN,
    }))
}

export async function geocodeAddress(
  address: string,
  province?: string,
  district?: string,
  signal?: AbortSignal,
): Promise<GeocodeResult | null> {
  const trimmed = address.trim()
  if (!trimmed) return null

  const parts = [trimmed, district, province, "Turkey"].filter(Boolean).join(", ")
  const params = new URLSearchParams({
    q: parts,
    format: "json",
    addressdetails: "0",
    limit: "1",
    countrycodes: "tr",
  })

  try {
    const res = await fetch(`${NOMINATIM_BASE}/search?${params.toString()}`, {
      method: "GET",
      headers: { Accept: "application/json" },
      signal,
    })

    if (!res.ok) return null

    const data = (await res.json()) as Array<{
      lat: string
      lon: string
      display_name: string
    }>

    if (!Array.isArray(data) || data.length === 0) return null

    const first = data[0]
    const lat = Number(first.lat)
    const lng = Number(first.lon)

    if (!Number.isFinite(lat) || !Number.isFinite(lng)) return null

    return {
      lat,
      lng,
      displayName: first.display_name,
    }
  } catch {
    return null
  }
}

export async function searchNeighborhoods(
  province: string,
  district: string,
  query: string,
  signal?: AbortSignal,
): Promise<NeighborhoodSuggestion[]> {
  const q = query.trim()
  if (q.length < 2 || !province || !district) return []

  const localResults = getLocalNeighborhoods(province, district, q)
  if (localResults.length > 0) return localResults

  const params = new URLSearchParams({
    q: `${q} Mahallesi, ${district}, ${province}, Turkey`,
    format: "json",
    countrycodes: "tr",
    addressdetails: "1",
    limit: "10",
  })

  try {
    const res = await fetch(`${NOMINATIM_BASE}/search?${params.toString()}`, {
      method: "GET",
      headers: { Accept: "application/json" },
      signal,
    })

    if (!res.ok) return []

    const data = (await res.json()) as Array<{
      lat: string
      lon: string
      display_name: string
      address?: {
        suburb?: string
        neighbourhood?: string
        quarter?: string
        village?: string
        hamlet?: string
        road?: string
      }
    }>

    const seen = new Set<string>()
    const suggestions: NeighborhoodSuggestion[] = []

    for (const item of data) {
      const addr = item.address ?? {}

      const name =
        addr.neighbourhood ||
        addr.suburb ||
        addr.quarter ||
        addr.village ||
        addr.hamlet ||
        addr.road ||
        ""

      if (!name) continue

      const key = normalizeTR(name)
      if (seen.has(key)) continue

      seen.add(key)

      suggestions.push({
        name,
        displayName: item.display_name,
        lat: Number(item.lat),
        lng: Number(item.lon),
      })
    }

    return suggestions
  } catch {
    return []
  }
}
